"""The House's lived-in clutter layer (art #104, Q21 = A; docs/house.md "Clutter"): small props from the dressing
library's `clutter` class (and a few others) added to every interior room's dressing file as a generated block.

Pure Python and deterministic: one `random.Random` per room seeded with SEED and the room id; `house --clutter` writes
the block at the end of `layouts/house/dressing/<room>.toml` after MARK (everything after MARK is replaced; edit RULES
and HOSTS here, not the block). The layers, in room-local metres like the dressing:
- surface clutter on the tops of HOSTS furniture (not a station's own prop: stations stay readable), up to
  `per_host` items each, kept apart from what already stands on the top (a lamp, a computer);
- wall dressing (frames, shelves, clocks) on free wall spans: on a real wall face, clear of door openings, windows,
  corners, the stairs and anything in front of the wall at its height;
- floor clutter (baskets, shoes, toys) against free wall spans, clear of doors, stations, spawns and the stairs, and a
  doormat inside the room's first door.
Every clutter item is non-solid (`collision = "none"` in the library, or under 0.3 m tall), so the walk's capsule and
the overlap rule do not see it.
"""
