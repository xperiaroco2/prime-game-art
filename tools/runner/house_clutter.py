WALL_H = {"picture_frame": 1.4, "wall_shelf": 1.45, "wall_clock": 1.85}  # the wall item's bottom above the floor
CORNER = 0.35  # no wall or floor item this close to a room corner
WINDOW_HALF = 1.15  # a window is 2 m wide: wall items keep this far from its centre
STAIR_GAP = 0.3

